import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
const context=vm.createContext({});
vm.runInContext(await readFile(new URL('../chrome-extension/playback.js',import.meta.url),'utf8'),context);
const root=items=>({querySelectorAll:()=>items});
const video={tagName:'VIDEO',paused:false,ended:false,readyState:3,currentTime:0};
const sample=context.createPlaybackReader();
assert.equal(sample(root([])),'not-playing');
assert.equal(sample(root([video])),'unknown');
video.currentTime=1;
assert.equal(sample(root([video])),'playing');
assert.equal(sample(root([video])),'unknown');
video.paused=true;
assert.equal(sample(root([video])),'not-playing');
assert.equal(sample(root([{tagName:'IFRAME',contentDocument:null}])),'unknown');
assert.equal(sample(root([{tagName:'CANVAS'}])),'unknown');
assert.equal(sample(root([{tagName:'DIV',shadowRoot:root([video])}])),'not-playing');
console.log('PASS: 8 playback assertions');
